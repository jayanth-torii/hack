import { Types } from "mongoose";
import { Roadmap, type RoadmapDocument, type Stage, type TimelineDay } from "../models/Roadmap";
import { CATALOG_FILTER } from "./catalog.service";
import { ApiError } from "../utils/apiError";
import { normalizeTopic, slugify } from "../utils/slugify";
import { distribute } from "../utils/seedCourses";

/**
 * The non-AI path to a personal roadmap: a learner assembles one from stages
 * they picked out of the published catalog.
 *
 * The point is that nothing is generated. Every stage is **copied** from a
 * curated course whose resources were already verified, so a built course is
 * exactly as trustworthy as the catalog it was drawn from, and building one
 * costs no model call and no rate-limit budget.
 *
 * The copy is deliberate rather than a reference. If a built course pointed at
 * the catalog's stages, re-seeding a curated course with `--force` would
 * silently rewrite somebody's personal path underneath them — and because
 * stage ids are regenerated by that seed, it would also orphan their progress.
 * A snapshot ages, but it never changes without the learner asking.
 */

export interface BuilderStageSelection {
  /** Catalog course the stage is taken from. */
  courseId: string;
  /** Stage within that course. */
  stageId: string;
}

export interface BuildCourseInput {
  title: string;
  selections: BuilderStageSelection[];
}

export const MAX_BUILDER_STAGES = 20;

/**
 * Same guard the generator and the seeder use: slugify, then suffix until the
 * slug is free. Two learners building "My Backend Path" must not collide on
 * the unique slug index.
 */
async function uniqueSlug(title: string): Promise<string> {
  const base = slugify(title) || "custom-course";
  let candidate = base;
  let suffix = 1;
  while (await Roadmap.exists({ slug: candidate })) {
    candidate = `${base}-${suffix}`;
    suffix += 1;
  }
  return candidate;
}

/**
 * One day per entry, numbered sequentially across the whole course, with each
 * stage's syllabus spread over that stage's estimated days. Mirrors the
 * curated seeder so a built course's calendar looks like every other one.
 */
export function buildTimelineFromStages(stages: Stage[]): TimelineDay[] {
  const timeline: TimelineDay[] = [];
  let day = 1;
  for (const stage of stages) {
    for (const chunk of distribute(stage.syllabus, Math.max(1, stage.estimatedDays))) {
      timeline.push({
        day,
        tasks: chunk.length > 0 ? chunk : [`Review and practice: ${stage.title}`],
      });
      day += 1;
    }
  }
  return timeline;
}

/**
 * Copies the selected stages, in the order given, into a fresh stage array.
 *
 * Each stage gets a **new** `_id` — the ids are the key `UserProgress` stores
 * completions against, so reusing the catalog's would make progress on the
 * built course and on the original course the same record. Picking the same
 * stage twice is allowed and yields two independent stages, which is why the
 * ids are minted per selection rather than per source stage.
 *
 * The prerequisite chain is rebuilt from the new order, not copied: the whole
 * point of building a course is choosing the sequence, and a copied
 * `prerequisiteStageId` would point into a different roadmap entirely and
 * leave every stage permanently locked.
 */
export function assembleStages(
  selections: BuilderStageSelection[],
  sources: Map<string, RoadmapDocument>
): Stage[] {
  const stageIds = selections.map(() => new Types.ObjectId());

  return selections.map((selection, index) => {
    const course = sources.get(selection.courseId);
    if (!course) {
      throw ApiError.badRequest(`Course ${selection.courseId} is not in the published catalog`);
    }
    const source = course.stages.find((s) => s._id.toString() === selection.stageId);
    if (!source) {
      throw ApiError.badRequest(
        `Stage ${selection.stageId} is not part of "${course.topic}"`
      );
    }

    return {
      _id: stageIds[index]!,
      order: index,
      title: source.title,
      type: source.type,
      difficulty: source.difficulty,
      prerequisiteStageId: index === 0 ? null : stageIds[index - 1]!,
      syllabus: [...source.syllabus],
      freeResources: source.freeResources.map((r) => ({ ...r })),
      certifications: source.certifications.map((c) => ({ ...c })),
      practiceLinks: source.practiceLinks.map((p) => ({ ...p })),
      estimatedDays: source.estimatedDays,
    };
  });
}

export interface BuiltCourse {
  roadmap: RoadmapDocument;
}

/**
 * Builds and persists the course. The caller is responsible for adding it to
 * the learner's library and recording the activity — this function only owns
 * the document.
 *
 * The result is **private**: `isPublicTemplate: false` keeps a personal
 * assembly out of everybody else's catalog, which is also what stops the
 * browse page filling up with one learner's experiments.
 */
export async function buildCourse(input: BuildCourseInput): Promise<BuiltCourse> {
  const { title, selections } = input;

  if (selections.length === 0) {
    throw ApiError.badRequest("Pick at least one stage to build a course");
  }
  if (selections.length > MAX_BUILDER_STAGES) {
    throw ApiError.badRequest(`A built course can hold at most ${MAX_BUILDER_STAGES} stages`);
  }

  const courseIds = [...new Set(selections.map((s) => s.courseId))];
  if (courseIds.some((id) => !Types.ObjectId.isValid(id))) {
    throw ApiError.badRequest("One of the selected courses has an invalid id");
  }

  // Only catalog courses are drawable — the same published-and-categorised
  // definition the browse page uses. Without this match a crafted request
  // could copy stages out of another learner's private built course, or out
  // of an uncurated generated roadmap the catalog never offered.
  const courses = await Roadmap.find({
    ...CATALOG_FILTER,
    _id: { $in: courseIds.map((id) => new Types.ObjectId(id)) },
  });
  const sources = new Map(courses.map((c) => [c._id.toString(), c]));

  const stages = assembleStages(selections, sources);
  const slug = await uniqueSlug(title);

  const roadmap = await Roadmap.create({
    topic: title.trim(),
    normalizedTopic: normalizeTopic(title),
    slug,
    // A built course is somebody's own path, not a catalog entry.
    isPublicTemplate: false,
    sourceModel: "custom",
    stages,
    suggestedTimeline: buildTimelineFromStages(stages),
  });

  return { roadmap };
}
